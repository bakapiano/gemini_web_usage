const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const destination = path.join(root, 'gemini-web-usage.user.js');
const repository = 'https://github.com/bakapiano/gemini_web_usage';
const raw = 'https://raw.githubusercontent.com/bakapiano/gemini_web_usage/main/gemini-web-usage.user.js';

function renderUserscript() {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
  const sourceFiles = manifest.content_scripts[0].js;
  const sources = sourceFiles.map(file => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n').trimEnd());
  return `// ==UserScript==
// @name         ${manifest.name}
// @namespace    ${repository}
// @version      ${manifest.version}
// @description  ${manifest.description}
// @match        https://gemini.google.com/*
// @run-at       document-idle
// @noframes
// @sandbox      DOM
// @grant        GM_getValue
// @grant        GM_setValue
// @homepageURL  ${repository}
// @supportURL   ${repository}/issues
// @updateURL    ${raw}
// @downloadURL  ${raw}
// ==/UserScript==

// Generated by scripts/build-userscript.cjs from ${sourceFiles.join(' and ')}.
(() => {
  'use strict';
${sources.join('\n\n').split('\n').map(line => line && `  ${line}`).join('\n')}
})();
`;
}

if (require.main === module) {
  const output = renderUserscript();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) {
      console.error('Userscript is out of date. Run: node scripts/build-userscript.cjs');
      process.exitCode = 1;
    }
  } else {
    fs.writeFileSync(destination, output, 'utf8');
    console.log(`Built ${path.basename(destination)}`);
  }
}

module.exports = { renderUserscript };
